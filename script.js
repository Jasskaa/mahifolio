const navToggle = document.getElementById("nav-toggle");
const offcanvas = document.getElementById("offcanvas-nav");
const offcanvasOverlay = document.getElementById("offcanvas-overlay");

function closeOffcanvas() {
  offcanvas.classList.remove("is-open");
  offcanvasOverlay.classList.remove("is-open");
  navToggle.classList.remove("is-active");
  navToggle.setAttribute("aria-expanded", "false");
  offcanvas.setAttribute("aria-hidden", "true");
}

function openOffcanvas() {
  offcanvas.classList.add("is-open");
  offcanvasOverlay.classList.add("is-open");
  navToggle.classList.add("is-active");
  navToggle.setAttribute("aria-expanded", "true");
  offcanvas.setAttribute("aria-hidden", "false");
}

if (navToggle && offcanvas && offcanvasOverlay) {
  navToggle.addEventListener("click", () => {
    if (offcanvas.classList.contains("is-open")) closeOffcanvas();
    else openOffcanvas();
  });
  offcanvasOverlay.addEventListener("click", closeOffcanvas);
  offcanvas.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeOffcanvas));
  document.addEventListener("keydown", (e) => { if (e.key === "Escape") closeOffcanvas(); });
}

// ================================================================
// Header scroll state + scroll progress bar (rAF-throttled)
// ================================================================
const siteHeader = document.querySelector(".site-header");
const scrollProgress = document.getElementById("scroll-progress");
let scrollTicking = false;

function onScrollFrame() {
  const scrollY = window.scrollY || window.pageYOffset;
  if (siteHeader) siteHeader.classList.toggle("is-scrolled", scrollY > 40);

  if (scrollProgress) {
    const docHeight = document.documentElement.scrollHeight - window.innerHeight;
    const pct = docHeight > 0 ? (scrollY / docHeight) * 100 : 0;
    scrollProgress.style.width = pct + "%";
  }
  scrollTicking = false;
}

window.addEventListener("scroll", () => {
  if (!scrollTicking) {
    requestAnimationFrame(onScrollFrame);
    scrollTicking = true;
  }
}, { passive: true });
onScrollFrame();

