const revealEls = document.querySelectorAll(".reveal");

function animateCounter(el) {
  const target = parseFloat(el.getAttribute("data-count"));
  const suffix = el.getAttribute("data-suffix") || "";
  if (isNaN(target)) return;
  const duration = 1200;
  const start = performance.now();

  function tick(now) {
    const progress = Math.min((now - start) / duration, 1);
    const eased = 1 - Math.pow(1 - progress, 3);
    const value = Math.round(target * eased);
    el.textContent = value + suffix;
    if (progress < 1) requestAnimationFrame(tick);
  }
  requestAnimationFrame(tick);
}

if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");

          const counter = entry.target.querySelector("[data-count]");
          if (counter && !counter.classList.contains("is-counted")) {
            counter.classList.add("is-counted");
            animateCounter(counter);
          }

          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.15, rootMargin: "0px 0px -40px 0px" }
  );

  revealEls.forEach((el) => observer.observe(el));

  const langBarsSection = document.querySelector(".skills");
  if (langBarsSection) {
    const barObserver = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            entry.target.querySelectorAll(".bar-fill").forEach((fill) => {
              fill.style.width = fill.getAttribute("data-width") + "%";
            });
            barObserver.unobserve(entry.target);
          }
        });
      },
      { threshold: 0.2 }
    );
    barObserver.observe(langBarsSection);
  }
} else {
  revealEls.forEach((el) => el.classList.add("is-visible"));
  document.querySelectorAll(".bar-fill").forEach((fill) => { fill.style.width = fill.getAttribute("data-width") + "%"; });
  document.querySelectorAll("[data-count]").forEach((el) => { el.textContent = el.getAttribute("data-count") + (el.getAttribute("data-suffix") || ""); });
}

